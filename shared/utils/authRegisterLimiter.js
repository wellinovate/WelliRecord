// /login/verify-code and /resend-verify-code had no dedicated limiter at
// all — every other route in auth_routes.js does. That left the actual
// OTP-brute-force and SMS-toll-fraud surface open behind only the generic
// 300-req/min global limiter, which is far too loose to stop someone
// grinding through a 6-digit code.
export const verifyLoginCodeLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 10,
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    success: false,
    message: "Too many verification attempts. Please try again later.",
  },
});

